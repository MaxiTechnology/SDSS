import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';

test('real browser journey: setup, evidence, price eligibility, matrix, scenario, decision and PDF',async({page,request})=>{
 const isolation=await request.get('/api/test-isolation');expect(await isolation.json()).toEqual({schema:process.env.SDSS_BROWSER_TEST_SCHEMA});
 const empty=await request.get('/api/projects');expect(await empty.json()).toEqual([]);
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/#/new');
 await page.getByLabel('Project Name').fill('Browser Journey — Synthetic');
 await page.getByLabel('Purchasing Category').selectOption('IT & Hardware');
 await page.getByLabel('Currency').selectOption('RUB');
 await page.getByLabel('Project Description').fill('Synthetic real-browser journey in isolated cloud storage.');
 await page.locator('form').getByRole('button',{name:'Create Project',exact:true}).click();
 await expect(page).toHaveURL(/#\/projects\/[0-9a-f-]+$/);
 await expect(page.getByRole('heading',{name:'Purchasing Project Details',exact:true})).toBeVisible();
 await expect(page.getByLabel('Project Name')).toBeDisabled();
 await page.reload();await expect(page.getByLabel('Project Name')).toHaveValue('Browser Journey — Synthetic');
 console.log('Saved project reopened from isolated cloud storage.');
 await page.getByRole('button',{name:'Continue to Add Suppliers',exact:false}).click();
 for(const name of ['Browser Supplier A','Browser Supplier B','Browser Supplier C']){
  await page.getByRole('button',{name:'+ Add Supplier',exact:true}).first().click();
  const dialog=page.getByRole('dialog');await dialog.getByLabel('Supplier Name').fill(name);
  await dialog.getByRole('button',{name:'Add Supplier',exact:true}).click();await expect(dialog).not.toBeVisible();
 }
 await page.getByRole('button',{name:'Continue to Criteria & Weights',exact:false}).click();
 await page.getByLabel('Enforce a maximum acceptable total price').check();
 await page.getByLabel('Maximum Total Price').fill('110');
 await page.getByRole('button',{name:'+ Add Mandatory Check',exact:true}).click();
 await page.getByLabel('Check Name',{exact:true}).fill('Synthetic document');
 await page.getByLabel('Pass Requirement').fill('Reviewer accepts the synthetic demonstration document.');
 await page.getByRole('button',{name:'Save Criteria',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('saved');
 console.log('Three suppliers and mandatory criteria saved through the UI.');
 await page.getByRole('button',{name:'Continue to Manual Weighting',exact:false}).click();
 await page.getByRole('button',{name:'Distribute Equally',exact:true}).click();
 await page.getByLabel('I have reviewed these weights and approve their use for evaluation.').check();
 await page.getByRole('button',{name:'Approve Weights',exact:true}).click();
 await expect(page.getByText('Manual weights approved and saved.',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Continue to Eligibility Review',exact:false}).click();
 await expect(page.getByRole('button',{name:'Continue to Evaluation Matrix',exact:false})).toBeDisabled();
 for(const [suffix,price] of [['A','100'],['B','120'],['C','110']]){
  await page.getByRole('button',{name:`Review Browser Supplier ${suffix}`,exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Link upload to requirement').selectOption({label:'Synthetic document'});
  await dialog.locator('input[type=file]').setInputFiles({name:`synthetic-${suffix}.txt`,mimeType:'text/plain',buffer:Buffer.from('Synthetic demonstration document only. Not a real certificate.\n')});
  await dialog.getByRole('button',{name:'Upload Document',exact:true}).click();
  await expect(dialog.getByRole('button',{name:`Download synthetic-${suffix}.txt`,exact:true})).toBeVisible();
  await dialog.getByLabel('Determination for Synthetic document').selectOption('passed');
  await dialog.getByLabel('Review notes for Synthetic document').fill('Reviewed uploaded synthetic demonstration text and accepted it.');
  await dialog.getByLabel('Supplier total price (RUB)').fill(price);
  await dialog.getByRole('button',{name:'Save Review',exact:true}).click();await expect(dialog).not.toBeVisible();
 }
 await expect(page.locator('tbody tr').filter({hasText:'Browser Supplier B'}).locator('.chip')).toHaveText('ineligible');
 await expect(page.locator('tbody tr').filter({hasText:'Browser Supplier C'}).locator('.chip')).toHaveText('eligible');
 console.log('Evidence uploaded; below/above/exact price eligibility verified.');
 await page.getByRole('button',{name:'Continue to Evaluation Matrix',exact:false}).click();
 await expect(page.getByRole('cell',{name:'Browser Supplier B',exact:true})).toHaveCount(0);
 for(const [name,values] of [['Browser Supplier A',['100','90','5','5','24']],['Browser Supplier C',['110','85','7','4','18']]] as const){
  for(const [i,criterion] of ['Price / Total Purchasing Cost','Product or Service Quality','Delivery Time','Supplier Reliability','Warranty'].entries())await page.getByLabel(`${name}: ${criterion}`,{exact:true}).fill(values[i]);
 }
 await page.getByRole('button',{name:'Save Matrix Draft',exact:true}).click();await expect(page.getByRole('status')).toContainText('Matrix saved');
 await page.getByRole('button',{name:'Calculate Rankings',exact:true}).click();
 await expect(page.locator('tbody tr')).toHaveCount(2);await expect(page.locator('tbody tr').first()).toContainText('Browser Supplier A');
 console.log('Eligible matrix saved and TOPSIS ranking calculated through the UI.');
 await page.getByRole('button',{name:'Run Sensitivity Analysis',exact:true}).click();
 for(const [name,value] of [['Price / Total Purchasing Cost','90'],['Product or Service Quality','3'],['Delivery Time','3'],['Supplier Reliability','2'],['Warranty','2']])await page.getByLabel(`${name} scenario weight`,{exact:true}).fill(value);
 await page.getByRole('button',{name:'Run Simulation',exact:true}).click();
 await page.getByLabel('Scenario name',{exact:true}).fill('Browser cost emphasis');
 await page.getByLabel('Scenario notes',{exact:true}).fill('Synthetic selected weight test; no automatic award.');
 await page.getByRole('button',{name:'Save Scenario',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Browser cost emphasis',exact:true})).toBeVisible();
 await page.reload();await expect(page.getByRole('heading',{name:'Browser cost emphasis',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Back to Rankings',exact:false}).click();
 await page.getByRole('button',{name:'Continue to Final Decision',exact:false}).click();
 await page.getByLabel('Decision reason',{exact:true}).fill('Synthetic approval: A ranked highest; B exceeded the maximum price.');
 await page.getByLabel('I have reviewed the ranking and confirm this purchasing decision.').check();
 await page.getByRole('button',{name:'Confirm Decision',exact:true}).click();
 await expect(page.getByText('Recommended supplier approved — version 1',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'View Decision Report',exact:true}).click();
 await expect(page.getByText('Selected supplier: Browser Supplier A',{exact:true})).toBeVisible();
 await expect(page.getByText('Mandatory maximum price: 110',{exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Download saved evidence: synthetic-A.txt',exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Download saved evidence: synthetic-C.txt',exact:true})).toBeVisible();
 await expect(page.getByText('Scenario: Browser cost emphasis',{exact:false})).toBeVisible();
 const evidenceDownload=page.waitForEvent('download');await page.getByRole('button',{name:'Download saved evidence: synthetic-C.txt',exact:true}).click();
 const evidence=await evidenceDownload;expect(evidence.suggestedFilename()).toBe('synthetic-C.txt');
 await evidence.saveAs('test-results/live-evidence.txt');expect(await readFile('test-results/live-evidence.txt','utf-8')).toBe('Synthetic demonstration document only. Not a real certificate.\n');
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Download PDF',exact:true}).click();
 await (await download).saveAs('test-results/live-report.pdf');
 expect((await readFile('test-results/live-report.pdf')).subarray(0,5).toString()).toBe('%PDF-');
 await page.reload();await expect(page.getByText('Scenario: Browser cost emphasis',{exact:false})).toBeVisible();
 await page.screenshot({path:'test-results/live-report.png',fullPage:true});
 await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name:'Dashboard',exact:true}).click();
 await expect(page.getByRole('button',{name:'All projects 1',exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Approved 1',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Saved Report',exact:true}).click();
 await expect(page.getByText('Selected supplier: Browser Supplier A',{exact:true})).toBeVisible();
 expect(errors).toEqual([]);
});
